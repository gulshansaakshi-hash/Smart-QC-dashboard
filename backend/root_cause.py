"""
Rule-Based Root Cause Analysis (RCA) Module.

Identifies possible manufacturing issues and recommended actions from
machine sensor readings using predefined IF/ELSE engineering rules.

Note: Root causes generated by this module are simulated suggestions
for academic demonstration and are NOT confirmed engineering diagnoses.
"""

import os
import sys

PROJECT_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if PROJECT_ROOT not in sys.path:
    sys.path.insert(0, PROJECT_ROOT)

from config import MACHINE_RPM_RANGES, SENSOR_RANGES

RCA_DISCLAIMER = (
    "Simulated suggestion for academic demonstration only — "
    "not a confirmed engineering diagnosis."
)


def _is_rpm_abnormal(machine_id, rpm):
    """Return True if RPM is outside the machine's configured normal range."""
    rpm_cfg = MACHINE_RPM_RANGES.get(machine_id, {"normal_min": 1000, "normal_max": 1800})
    return rpm < rpm_cfg["normal_min"] or rpm > rpm_cfg["normal_max"]


def identify_root_cause(reading, sensor_type=None):
    """
    Evaluate predefined rules against a sensor reading dictionary.
    Returns a dictionary with:
        - issue
        - possible_cause
        - recommended_action
        - note
    """
    machine_id = reading["machine_id"]
    temp = float(reading["temperature"])
    vib = float(reading["vibration"])
    pres = float(reading["pressure"])
    rpm = int(reading["rpm"])
    speed = int(reading["production_speed"])

    temp_crit = SENSOR_RANGES["temperature"]["warning_max"]   # 85°C
    vib_crit = SENSOR_RANGES["vibration"]["warning_max"]      # 7 mm/s
    pres_min = SENSOR_RANGES["pressure"]["normal_min"]        # 4 bar
    pres_max = SENSOR_RANGES["pressure"]["normal_max"]        # 9 bar
    low_speed = SENSOR_RANGES["production_speed"]["low_threshold"]
    rpm_abnormal = _is_rpm_abnormal(machine_id, rpm)

    # Rule 1: High temperature AND high vibration -> Bearing wear or friction
    if temp > temp_crit and vib > vib_crit:
        return {
            "issue": "High temperature and excessive vibration",
            "possible_cause": "Bearing wear or friction",
            "recommended_action": "Inspect bearing lubrication and mechanical condition.",
            "note": RCA_DISCLAIMER,
        }

    # Rule 2: High vibration AND abnormal RPM -> Shaft misalignment
    if vib > vib_crit and rpm_abnormal:
        return {
            "issue": "Excessive vibration with abnormal RPM",
            "possible_cause": "Shaft misalignment",
            "recommended_action": "Inspect shaft alignment and coupling balance.",
            "note": RCA_DISCLAIMER,
        }

    # Rule 3: High temperature AND low production speed -> Machine overheating
    if temp > temp_crit and speed < low_speed:
        return {
            "issue": "High temperature with low production speed",
            "possible_cause": "Machine overheating",
            "recommended_action": "Inspect cooling system and operating load conditions.",
            "note": RCA_DISCLAIMER,
        }

    # Rule 4: Pressure below 4 bar -> Hydraulic pressure loss
    if pres < pres_min:
        return {
            "issue": "Low hydraulic pressure",
            "possible_cause": "Hydraulic pressure loss",
            "recommended_action": "Inspect hydraulic connections, seals, and pump output.",
            "note": RCA_DISCLAIMER,
        }

    # Rule 5: Pressure above 9 bar -> Excessive hydraulic pressure
    if pres > pres_max:
        return {
            "issue": "High hydraulic pressure",
            "possible_cause": "Excessive hydraulic pressure",
            "recommended_action": "Inspect pressure control valve and regulator settings.",
            "note": RCA_DISCLAIMER,
        }

    # Single-sensor fallback rules
    if sensor_type == "Temperature" or temp > SENSOR_RANGES["temperature"]["normal_max"]:
        return {
            "issue": "Elevated operating temperature",
            "possible_cause": "Insufficient cooling or heavy cutting load",
            "recommended_action": "Check coolant flow and reduce spindle load if needed.",
            "note": RCA_DISCLAIMER,
        }

    if sensor_type == "Vibration" or vib > SENSOR_RANGES["vibration"]["normal_max"]:
        return {
            "issue": "Elevated machine vibration",
            "possible_cause": "Tool wear or loose mounting fixture",
            "recommended_action": "Inspect cutting tool condition and machine mounting bolts.",
            "note": RCA_DISCLAIMER,
        }

    if sensor_type == "RPM" or rpm_abnormal:
        return {
            "issue": "Abnormal spindle RPM",
            "possible_cause": "Motor drive fluctuation or speed controller drift",
            "recommended_action": "Check VFD/motor controller settings and belt tension.",
            "note": RCA_DISCLAIMER,
        }

    return {
        "issue": "Statistical sensor deviation (Z-score > 3)",
        "possible_cause": "Unusual operating pattern compared to recent baseline",
        "recommended_action": "Monitor machine closely and schedule preventive check.",
        "note": RCA_DISCLAIMER,
    }

